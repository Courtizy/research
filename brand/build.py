"""Generate the web assets from palette.py (standard library only).

    python brand/build.py

Writes, next to this file:
    tokens.json        every value, for any tool that reads JSON
    css/brand.css      CSS variables (light + dark) and a few components
    js/palette.js      ES module for charts in the browser
    icons/*.svg        app tiles, mark-only icons, and favicons

PNG images (favicons, README banners, social previews) come from render.py,
which needs Playwright. Re-run both after changing palette.py.
"""

from __future__ import annotations

import json
from pathlib import Path

import palette as p

HERE = Path(__file__).resolve().parent
HEADER = "Generated by brand/build.py from brand/palette.py. Do not edit by hand."


# --------------------------------------------------------------------------- css
def _mode_block(mode: str, indent: str = "  ") -> str:
    s = p.SURFACE[mode]
    lines = [f"color-scheme: {mode};"]
    lines += [f"--{k.replace('_', '-')}: {v};" for k, v in s.items()]
    lines += [f"--c-{k}: {v};" for k, v in p.SERIES[mode].items()]
    lines += [f"--accent-{a}: {p.ACCENT_TEXT[mode][a]};" for a in p.APPS]
    lines += [f"--status-{k}: {v};" for k, v in p.STATUS[mode].items()]
    lines += [f"--status-{k}-text: {v};" for k, v in p.STATUS_TEXT[mode].items()]
    lines += [f"--div-{i + 1}: {c};" for i, c in enumerate(p.DIVERGING[mode])]
    return "\n".join(indent + line for line in lines)


def _app_block(app: str) -> str:
    lines = [f"  --brand-fill: {p.BRAND_FILL[app]};", f"  --accent: var(--accent-{app});"]
    lines += [f"  --series-{i + 1}: var(--c-{k});" for i, k in enumerate(p.SERIES_ORDER[app])]
    lines += [f"  --seq-{i + 1}: {c};" for i, c in enumerate(p.SEQUENTIAL[app])]
    return "\n".join(lines)


