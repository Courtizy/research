# ---------------------------------------------------------------------------- js
def build_js() -> str:
    data = json.dumps(p.all_tokens(), indent=2, ensure_ascii=False)
    return f"""// {HEADER}
// Usage:
//   import {{ series, currentMode, plotlyLayout }} from "./brand/js/palette.js";
//   const colors = series("tps");          // slot 1 = the app's own color
//   Plotly.newPlot(el, data, plotlyLayout("tps"));

export const tokens = {data};

/** "dark" or "light", honoring data-theme on <html>, then the OS setting. */
export function currentMode() {{
  const forced = document.documentElement.dataset.theme;
  if (forced === "dark" || forced === "light") return forced;
  return window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
}}

/** Chart colors for n series (max {p.MAX_SERIES}). Slot 1 is the app's own color. */
export function series(app, mode = currentMode(), n = tokens.maxSeries) {{
  if (n < 1 || n > tokens.maxSeries) {{
    throw new Error(`${{n}} series requested; max is ${{tokens.maxSeries}}. Fold the rest into "Other" or use small multiples.`);
  }}
  return tokens.apps[app].seriesOrder.slice(0, n).map((k) => tokens.series[mode][k]);
}}

/** Low -> high magnitude ramp in the app's hue. In dark mode, low sits near the surface. */
export function sequential(app, mode = currentMode()) {{
  const ramp = [...tokens.apps[app].sequential];
  return mode === "dark" ? ramp.reverse() : ramp;
}}

export const diverging = (mode = currentMode()) => [...tokens.diverging[mode]];
export const status = (mode = currentMode()) => ({{ ...tokens.status[mode] }});
export const surface = (mode = currentMode()) => ({{ ...tokens.surface[mode] }});

/** Re-run a chart's draw function when the color mode changes. */
export function onModeChange(callback) {{
  const mq = window.matchMedia("(prefers-color-scheme: light)");
  const fire = () => callback(currentMode());
  mq.addEventListener("change", fire);
  new MutationObserver(fire).observe(document.documentElement, {{ attributes: true, attributeFilter: ["data-theme"] }});
}}

/** A Plotly.js layout with this app's colors. Merge your own settings on top. */
export function plotlyLayout(app, mode = currentMode()) {{
  const s = tokens.surface[mode];
  const axis = {{
    gridcolor: s.line, linecolor: s.line, zerolinecolor: s.line,
    tickfont: {{ color: s.ink_muted }}, title: {{ font: {{ color: s.ink_secondary }} }},
  }};
  return {{
    colorway: series(app, mode),
    paper_bgcolor: s.page,
    plot_bgcolor: s.page,
    font: {{ family: "Space Grotesk, system-ui, sans-serif", color: s.ink }},
    xaxis: axis,
    yaxis: axis,
    legend: {{ font: {{ color: s.ink_secondary }} }},
    hoverlabel: {{ bgcolor: s.panel, bordercolor: s.line, font: {{ color: s.ink }} }},
  }};
}}
"""


# ------------------------------------------------------------------------- icons
def _svg(inner: str, size: int = 64) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
            f'viewBox="0 0 64 64">{inner}</svg>\n')


def _strokes(key: str, color: str, transform: str = "") -> str:
    t = f' transform="{transform}"' if transform else ""
    return (f'<g fill="none" stroke="{color}" color="{color}" stroke-width="4" '
            f'stroke-linecap="round" stroke-linejoin="round"{t}>{p.ICON_PATHS[key]}</g>')


def build_icons() -> dict[str, str]:
    out: dict[str, str] = {}
    shrink = "translate(9.6 9.6) scale(0.7)"  # mark at 70% inside the tile
    for app in p.APPS:
        tile = f'<rect width="64" height="64" fill="{p.BRAND_FILL[app]}"/>' + _strokes(app, p.ON_BRAND_FILL, shrink)
        out[f"{app}.svg"] = _svg(tile)
        out[f"{app}-mark.svg"] = _svg(_strokes(app, "currentColor"))
    core_tile = (f'<rect x="1.5" y="1.5" width="61" height="61" fill="{p.SURFACE["dark"]["panel"]}" '
                 f'stroke="{p.CORE_OUTLINE}" stroke-width="3"/>' + _strokes("core", p.SURFACE["dark"]["ink"], shrink))
    out["core.svg"] = _svg(core_tile)
    out["core-mark.svg"] = _svg(_strokes("core", "currentColor"))
    return out


def main() -> None:
    (HERE / "css").mkdir(exist_ok=True)
    (HERE / "js").mkdir(exist_ok=True)
    (HERE / "icons").mkdir(exist_ok=True)
    (HERE / "tokens.json").write_text(json.dumps(p.all_tokens(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / "css" / "brand.css").write_text(build_css(), encoding="utf-8")
    (HERE / "js" / "palette.js").write_text(build_js(), encoding="utf-8")
    for name, svg in build_icons().items():
        (HERE / "icons" / name).write_text(svg, encoding="utf-8")
    print("Wrote tokens.json, css/brand.css, js/palette.js and", len(build_icons()), "icons.")


if __name__ == "__main__":
    main()
